"""
Writing a session the legacy application will accept.

The api can authenticate a browser that logged in to the station
(:mod:`libretime_api.core.auth.php_session`), and this module closes the other
half: a browser that logs in to the api is logged in to the station as well. That
matters because the migration is long - a new screen and a legacy screen will be
open in the same tab session for a release or two - and a user should not have to
prove who they are twice, nor should the api have to keep a second idea of "logged
in" with its own expiry, its own logout and its own bugs.

What makes this possible is that the legacy application keeps its sessions in the
database rather than in php's files, and reads them through
``Zend_Session_SaveHandler_DbTable``, whose ``read()`` accepts any row whose
``modified + lifetime`` has not passed and hands back ``data`` unchanged. So a row
written here is a session, to both applications.

What it has to look like is set by ``application/Bootstrap.php``: the handler
columns, ``serialize_handler = php_serialize``, and the identity that
``LoginController::indexAction`` stores - the whole ``cc_subjs`` row as a
``stdClass``, kept under the ``libretime`` session namespace.
"""

from __future__ import annotations

import hashlib
import secrets
import time
from datetime import date, datetime, time as time_of_day

from django.db import connection

from ..models import Session, User
from ._phpserialize import PhpDecodeError, PhpObject, dumps, loads

# Taken from the php configuration of the legacy service rather than invented:
# a session the api writes has to expire the way one php writes expires, or the
# two applications disagree about when somebody is logged out. A station that
# changes these in php.ini has to change them here too - there is no config knob
# for them because there is none in php's session handling either, beyond the ini.
SESSION_LIFETIME = 1440  # session.gc_maxlifetime
SESSION_ID_LENGTH = 26  # session.sid_length
# session.sid_bits_per_character = 5, whose alphabet php spells out in that range.
# An id outside it is not invalid to the session handler, but it is a sign the id
# was not generated by a session at all, and worth not attracting.
SESSION_ID_ALPHABET = "0123456789abcdefghijklmnopqrstuv"

# The namespace Zend_Auth writes, and the one the csrf token lives in. Both are
# read by name in the legacy application: Application_Model_Auth and
# SecurityHelper::verifyCSRFToken.
AUTH_NAMESPACE = "libretime"
IDENTITY_KEY = "storage"
CSRF_NAMESPACE = "csrf_namespace"
CSRF_KEY = "authtoken"
# Zend_Session_Namespace bookkeeping ("ENT" is when the namespace was entered).
# Real rows carry it; a session without it reads the same, but it is cheap to be
# indistinguishable.
FRAMEWORK_KEY = "__ZF"


def new_session_id() -> str:
    """A session id in the shape php generates, and of the same strength."""
    return "".join(
        secrets.choice(SESSION_ID_ALPHABET) for _ in range(SESSION_ID_LENGTH)
    )


def new_csrf_token() -> str:
    """
    The token ``PageLayoutInitPlugin`` would have made: a sha1, in hex.

    ``secrets`` rather than ``openssl_random_pseudo_bytes``, which is what php
    uses there; both are asked for the same thing - 160 bits nobody can guess.
    """
    return hashlib.sha1(secrets.token_bytes(20)).hexdigest()


def identity(user: User) -> PhpObject:
    """
    The ``cc_subjs`` row as the legacy login hands it to ``Zend_Auth``.

    Read with ``SELECT *`` on purpose: the row object the legacy adapter stores is
    whatever the database returns, in column order, and it is not this code's job
    to decide which columns belong in a session. That is also the finding worth
    reporting upstream - ``getResultRowObject(null, 'password')`` intends to drop
    the password and drops nothing, because the column is called ``pass``, so the
    password hash travels into every session row. This reproduces the shape
    because the legacy application reads that row back; it is not an endorsement.
    """
    with connection.cursor() as cursor:
        cursor.execute("SELECT * FROM cc_subjs WHERE id = %s", [user.pk])

        if cursor.rowcount < 1:
            raise User.DoesNotExist(f"user {user.pk} is gone")

        columns = [column.name for column in cursor.description]
        values = cursor.fetchone()

    return PhpObject(
        (name, _as_php_value(value)) for name, value in zip(columns, values)
    )


def _as_php_value(value: object) -> object:
    """
    What php's driver would have handed Propel for this column.

    Integers arrive as integers and everything else as text, which is why a
    timestamp in a session row is a string and not an object.
    """
    if isinstance(value, datetime):
        # Postgres prints a second with no fractional part as "SS", and with one
        # as "SS.ffffff"; matching it keeps a rewritten row identical to the row
        # the legacy application wrote.
        text = value.strftime("%Y-%m-%d %H:%M:%S")

        return f"{text}.{value.microsecond:06d}" if value.microsecond else text

    if isinstance(value, (date, time_of_day)):
        return str(value)

    return value


def create(user: User) -> Session:
    """
    Open a session for ``user`` and return its row.

    A new id every time, never the caller's existing one: the legacy login calls
    ``Zend_Session::regenerateId()`` for the same reason, that a session id handed
    out before authentication must not survive it.
    """
    now = int(time.time())
    csrf_token = new_csrf_token()

    payload = {
        AUTH_NAMESPACE: {IDENTITY_KEY: identity(user)},
        CSRF_NAMESPACE: {CSRF_KEY: csrf_token},
        FRAMEWORK_KEY: {CSRF_NAMESPACE: {"ENT": now}},
    }

    return Session.objects.create(
        id=new_session_id(),
        updated_at=now,
        lifetime=SESSION_LIFETIME,
        data=dumps(payload),
    )


def destroy(session: Session) -> None:
    """
    Log a session out the way ``LoginController::logoutAction`` does.

    The row is not deleted: the identity is cleared and the csrf namespace is
    dropped, and the row itself goes away whenever the garbage collector finds it
    has expired. Deleting it here would be a different shape of correct, and the
    legacy application would not notice - but a station reading its own session
    table to see who is logged out would.

    Anything else in the row - a language choice, a screen's saved state - is
    left alone, as it is there.
    """
    payload = None

    if session.data:
        try:
            payload = loads(session.data)
        except PhpDecodeError:
            # Nothing readable to clear. Starting the row over is what php itself
            # ends up with after a logout: an empty session.
            payload = None

    if isinstance(payload, dict):
        payload.pop(CSRF_NAMESPACE, None)
        namespaced = payload.get(AUTH_NAMESPACE)

        if isinstance(namespaced, dict):
            namespaced[IDENTITY_KEY] = None
    else:
        payload = {}

    session.data = dumps(payload)
    session.updated_at = int(time.time())
    session.save(update_fields=["data", "updated_at"])
