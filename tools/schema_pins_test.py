"""The schema's formatter has to be pinned in one place and provably the same elsewhere.

api/schema.yml is generated by `make -C api schema` and formatted by prettier. It is
excluded from the repository's prettier pre-commit hook — see the `exclude` line beside
that hook — so the Makefile is the only thing that ever formats it. That makes two things
worth asserting, because both fail in someone else's pull request rather than here:

  - the version the Makefile pins must be the version the rest of the repository is
    formatted with, or the same file gets two house styles;
  - the development image must actually carry node, since the Makefile now fails instead
    of skipping the step when it is missing.
"""

import re
from pathlib import Path

from tools.packages import list_packages

ROOT = Path(__file__).resolve().parent.parent

# The same three components the dev image workflow asks for (dev-tools.yml), as absolute
# paths so the test does not depend on which directory pytest was started from.
DEVELOPMENT_IMAGE_PACKAGES = [ROOT / name for name in ("analyzer", "playout", "shared")]
DISTRIBUTIONS = ["bookworm", "noble", "trixie", "resolute"]


def prettier_hook_rev() -> str:
    """The rev of the prettier hook in .pre-commit-config.yaml."""
    config = (ROOT / ".pre-commit-config.yaml").read_text(encoding="utf-8")

    match = re.search(
        r"repo: https://github.com/jooola/pre-commit-prettier\s*\n\s*rev: (\S+)",
        config,
    )

    assert match, "no prettier hook in .pre-commit-config.yaml to compare against"

    return match.group(1)


def schema_formatter_version() -> str:
    """PRETTIER_VERSION from api/Makefile."""
    makefile = (ROOT / "api" / "Makefile").read_text(encoding="utf-8")

    match = re.search(r"^PRETTIER_VERSION \?= (\S+)$", makefile, flags=re.M)

    assert match, "api/Makefile does not pin PRETTIER_VERSION"

    return match.group(1)


def test_schema_formatter_matches_the_repositorys_prettier():
    assert schema_formatter_version() == prettier_hook_rev(), (
        "api/Makefile and .pre-commit-config.yaml disagree about prettier: the generated "
        "document would be formatted with a different version than every other yaml file "
        "in the repository"
    )


def test_schema_is_left_to_the_makefile():
    """
    If the pre-commit hook ever starts covering api/schema.yml, the exclusion in
    .pre-commit-config.yaml and this test need to be revisited together: two formatters
    for one generated file is how formatting-only diffs come back.
    """
    config = (ROOT / ".pre-commit-config.yaml").read_text(encoding="utf-8")

    assert r"^api/schema.yml" in config, (
        "api/schema.yml is no longer excluded from the prettier hook; decide which of the "
        "two formatters owns this file"
    )


def test_development_image_carries_node():
    """
    `make -C api schema` formats unconditionally, on the assumption that the environment
    it is run in has node. That environment is the development image built by
    dev-tools.yml from these package lists.
    """
    for distribution in DISTRIBUTIONS:
        packages = list_packages(DEVELOPMENT_IMAGE_PACKAGES, distribution, True)

        assert "nodejs" in packages, f"no node in the {distribution} dev image"
        assert "npm" in packages, f"no npm in the {distribution} dev image"


def test_node_stays_out_of_the_production_image():
    """
    Only the development image needs a javascript formatter. Without this, an edit to the
    ini file could put node into every station install by accident, since the same lists
    feed the production packages.
    """
    for distribution in DISTRIBUTIONS:
        packages = list_packages(DEVELOPMENT_IMAGE_PACKAGES, distribution, False)

        assert "nodejs" not in packages
        assert "npm" not in packages
